// Foto usada em todas as avaliações (esse arquivo existe no seu projeto)
const FOTO_PADRAO = "assets/img/ui/paw.png";

// Mistura as avaliações para escolher quatro diferentes.
function embaralharAvaliacoes(lista) {
  const copia = [...lista];

  for (let i = copia.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copia[i], copia[j]] = [copia[j], copia[i]];
  }

  return copia;
}

// Cria o HTML de cada avaliação.
function criarAvaliacao(avaliacao) {
  const artigo = document.createElement("article");
  artigo.className = "avaliacao";

  const autor = document.createElement("div");
  autor.className = "avaliacao__autor";

  const avatar = document.createElement("span");
  avatar.className = "avaliacao__avatar";

  const foto = document.createElement("img");
  foto.src = FOTO_PADRAO;
  foto.alt = "";
  foto.width = 36;
  foto.height = 40;

  avatar.appendChild(foto);
  autor.append(
    avatar,
    document.createTextNode(` ${avaliacao.nome} · ${avaliacao.tipoPet}`)
  );

  const bloco = document.createElement("blockquote");
  const mensagem = document.createElement("p");
  mensagem.textContent = `“${avaliacao.mensagem}”`;
  bloco.appendChild(mensagem);

  const patas = document.createElement("div");
  patas.className = "avaliacao__patas";
  patas.setAttribute("role", "img");
  patas.setAttribute("aria-label", `${avaliacao.estrelas} de 5 patinhas`);

  for (let i = 0; i < 5; i++) {
    const pata = document.createElement("img");
    pata.src = "assets/img/ui/paw.png";
    pata.alt = "";
    pata.width = 36;
    pata.height = 40;

    if (i >= avaliacao.estrelas) {
      pata.style.opacity = "0.25";
    }

    patas.appendChild(pata);
  }

  artigo.append(autor, bloco, patas);
  return artigo;
}

// Exibe quatro avaliações aleatórias.
function trocarAvaliacoes() {
  const grade = document.querySelector(".avaliacoes__grade");

  if (!grade) {
    console.error("Não encontrei .avaliacoes__grade no HTML.");
    return;
  }

  const selecionadas = embaralharAvaliacoes(avaliacoes).slice(0, 4);
  grade.replaceChildren(...selecionadas.map(criarAvaliacao));
}

// Como o script tem defer, o HTML já está pronto quando ele roda.
if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", trocarAvaliacoes);
} else {
  trocarAvaliacoes();
}